// Enhance the existing Cloudflare Pages product response without changing shop logic.
const esc = v => String(v ?? '').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
export async function onRequestGet(context) {
  // context.next() lets Pages serve the existing HTML asset using its own routing.
  const original = await context.next();
  if (!original.ok || !original.headers.get('content-type')?.includes('text/html')) return original;
  const id = new URL(context.request.url).searchParams.get('id');
  if (!id || id.length > 150 || !context.env.DB) return original;
  let p;
  try {
    p = await context.env.DB.prepare('SELECT id,name,description,image_url,price_cents FROM products WHERE active=1 AND id=?').bind(id).first();
  } catch { return original; }
  if (!p) return original;
  const url='https://www.maelinne.ie/product?id='+encodeURIComponent(p.id);
  const description=String(p.description||('Shop '+p.name+' at MaeLinne Ireland.')).replace(/\s+/g,' ').trim().slice(0,155);
  const test=/^TEST ONLY/i.test(p.name);
  // Structured Product JSON-LD is generated by product.html from the live public catalogue.
  // Avoid a second, incomplete Product item that Google marks invalid.
  // Keep server-side title, description, canonical URL and test-product noindex.
  // Social sharing tags are metadata only: no visible page or shop controls change.
  const title=p.name+' | MaeLinne Ireland';
  const imageValue=String(p.image_url||'');
  const productImage=(imageValue.startsWith('/api/images/')||imageValue.startsWith('/assets/'))?'https://www.maelinne.ie'+imageValue:/^https:\/\/[^\s"'<>]+$/i.test(imageValue)?imageValue:'';
  const social='<meta property="og:type" content="product"><meta property="og:site_name" content="MaeLinne"><meta property="og:title" content="'+esc(title)+'"><meta property="og:description" content="'+esc(description)+'"><meta property="og:url" content="'+esc(url)+'">'+(productImage?'<meta property="og:image" content="'+esc(productImage)+'"><meta name="twitter:card" content="summary_large_image">':'');
  const meta='<title>'+esc(title)+'</title><meta name="description" content="'+esc(description)+'"><link rel="canonical" href="'+esc(url)+'">'+social+(test?'<meta name="robots" content="noindex,follow">':'');
  const html=(await original.text()).replace(/<title>[^<]*<\/title>/i,meta);
  const headers=new Headers(original.headers);
  headers.delete('content-length');
  headers.set('cache-control','no-store');
  return new Response(html,{status:original.status,headers});
}
